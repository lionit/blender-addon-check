"""Collect the most-downloaded add-ons from extensions.blender.org.

Writes config/addons.generated.json with one entry per add-on, in the same shape as
config/addons.json, using the platform's JSON API for metadata and the public
listing sorted by downloads for the ranking.

Usage:
    python scripts/collect_extensions.py --top 60
"""

from __future__ import annotations

import argparse
import re

from common import CONFIG_DIR, http_get, http_get_json, log, write_json

API_URL = "https://extensions.blender.org/api/v1/extensions/"
LISTING_URL = "https://extensions.blender.org/add-ons/?sort=downloads&page={page}"
SLUG_RE = re.compile(r'href="/add-ons/([a-z0-9][a-z0-9_-]*)/"')


def linux_capable(ext: dict) -> bool:
    platforms = ext.get("platforms") or []
    return not platforms or "linux-x64" in platforms


def fetch_api_index() -> dict[str, dict]:
    """One entry per add-on id. The API lists one row per build (platform x Blender range),
    so rows are grouped: `builds` keeps every Linux-capable build, newest minimum version first."""
    payload = http_get_json(API_URL)
    data = payload["data"] if isinstance(payload, dict) else payload
    index: dict[str, dict] = {}
    skipped: set[str] = set()
    for ext in data:
        if ext.get("type") != "add-on":
            continue
        if not linux_capable(ext):
            skipped.add(ext["id"])
            continue
        build = {
            "archive_url": ext.get("archive_url", ""),
            "version": ext.get("version", ""),
            "blender_version_min": ext.get("blender_version_min", ""),
            "blender_version_max": ext.get("blender_version_max", ""),
            "platforms": ext.get("platforms") or [],
        }
        entry = index.setdefault(ext["id"], {**ext, "builds": []})
        entry["builds"].append(build)
    for entry in index.values():
        entry["builds"].sort(key=lambda b: tuple(int(x) for x in (b["blender_version_min"] or "0").split(".") if x.isdigit()), reverse=True)
        newest = entry["builds"][0]
        for k in ("archive_url", "version", "blender_version_min", "blender_version_max"):
            entry[k] = newest[k]
    windows_only = skipped - set(index)
    log(f"api lists {len(index)} add-ons with a Linux build; {len(windows_only)} skipped as Windows/macOS-only")
    return index


def fetch_ranking(max_pages: int) -> list[str]:
    """Add-on slugs in download order, scraped from the public listing pages."""
    seen: list[str] = []
    for page in range(1, max_pages + 1):
        html = http_get(LISTING_URL.format(page=page)).decode("utf-8", "replace")
        slugs: list[str] = []
        for s in SLUG_RE.findall(html):  # each card links its slug more than once
            if s not in seen and s not in slugs:
                slugs.append(s)
        if not slugs:
            break
        seen.extend(slugs)
        log(f"page {page}: {len(slugs)} new slugs, {len(seen)} total")
    return seen


def to_entry(ext: dict) -> dict:
    return {
        "id": ext["id"],
        "name": ext.get("name") or ext["id"],
        "group": "extensions-top",
        "developer": ext.get("maintainer") or "",
        "homepage": ext.get("website") or f"https://extensions.blender.org/add-ons/{ext['id']}/",
        "version": ext.get("version", ""),
        "blender_version_min": ext.get("blender_version_min", ""),
        "blender_version_max": ext.get("blender_version_max", ""),
        "source": {"type": "extensions", "id": ext["id"], "archive_url": ext.get("archive_url", ""), "builds": ext.get("builds", [])},
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--top", type=int, default=60, help="how many add-ons to keep")
    ap.add_argument("--max-pages", type=int, default=30, help="listing pages to scan for the ranking")
    args = ap.parse_args()

    index = fetch_api_index()
    ranking = fetch_ranking(args.max_pages)
    entries = []
    for slug in ranking:
        ext = index.get(slug)
        if ext is None:
            continue
        entries.append(to_entry(ext))
        if len(entries) >= args.top:
            break
    if len(entries) < args.top:
        log(f"warning: ranking yielded only {len(entries)} add-ons; filling from API order")
        for slug, ext in index.items():
            if slug not in {e["id"] for e in entries}:
                entries.append(to_entry(ext))
            if len(entries) >= args.top:
                break
    write_json(CONFIG_DIR / "addons.generated.json", {"_comment": "Generated by scripts/collect_extensions.py; do not edit by hand.", "addons": entries})
    log(f"wrote {len(entries)} add-ons")


if __name__ == "__main__":
    main()
